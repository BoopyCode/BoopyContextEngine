/**
 * The blog's data layer: reads GitHub and turns repositories into articles.
 *
 * No build step, no dependencies, no API key (public search + contents API; 60 requests/hour
 * unauthenticated, set GITHUB_TOKEN to raise it).
 *
 * Two distinct reads, because a blog needs both:
 *  - `searchRepositories` - discovery, the same call a human makes in the GitHub UI;
 *  - `readRepository`     - the article material: README text and the raw file list.
 *
 * Both record their bytes so the measurement harness can attribute token cost honestly.
 */

const API = 'https://api.github.com';
const USER_AGENT = 'bce-blog';

export const POST_PLAN = [
  { slug: 'agent-frameworks', title: 'Where agent frameworks are heading', query: 'topic:ai-agents stars:>2000 pushed:>2026-06-01' },
  { slug: 'developer-tooling', title: 'Developer tooling worth a look', query: 'topic:developer-tools stars:>3000 pushed:>2026-06-01' },
  { slug: 'typescript-ecosystem', title: 'The TypeScript ecosystem in 2026', query: 'language:typescript stars:>5000 pushed:>2026-08-01' }
];

function headers() {
  const base = { 'User-Agent': USER_AGENT, Accept: 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28' };
  return process.env.GITHUB_TOKEN ? { ...base, Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : base;
}

async function getJson(path, attempt = 0) {
  try {
    const response = await fetch(`${API}${path}`, { headers: headers(), signal: AbortSignal.timeout(30000) });
    if (!response.ok) {
      throw new Error(`${path} -> HTTP ${response.status}`);
    }
    const text = await response.text();
    return { json: JSON.parse(text), bytes: Buffer.byteLength(text) };
  } catch (error) {
    const transient = !/HTTP \d+/.test(String(error?.message));
    if (transient && attempt < 2) {
      await new Promise((resolve) => setTimeout(resolve, 600 * (attempt + 1)));
      return getJson(path, attempt + 1);
    }
    throw error;
  }
}

/** Discovery: one search call, same shape a human gets from github.com/search. */
export async function searchRepositories(query, perPage = 10) {
  const { json, bytes } = await getJson(`/search/repositories?q=${encodeURIComponent(query)}&sort=stars&order=desc&per_page=${perPage}`);
  return {
    bytes,
    repositories: (json.items ?? []).map((repo) => ({
      name: repo.full_name,
      description: repo.description,
      stars: repo.stargazers_count,
      forks: repo.forks_count,
      language: repo.language,
      topics: repo.topics ?? [],
      pushedAt: repo.pushed_at,
      createdAt: repo.created_at,
      license: repo.license?.spdx_id ?? null,
      archived: repo.archived,
      homepage: repo.homepage
    }))
  };
}

/** Article material: README plus a shallow file listing, both as the API returns them. */
export async function readRepository(fullName) {
  const [readme, tree] = await Promise.all([
    getJson(`/repos/${fullName}/readme`).catch(() => ({ json: undefined, bytes: 0 })),
    getJson(`/repos/${fullName}/contents/`).catch(() => ({ json: [], bytes: 0 }))
  ]);
  const readmeText = readme.json?.content ? Buffer.from(readme.json.content, 'base64').toString('utf8') : '';
  const files = Array.isArray(tree.json)
    ? tree.json.slice(0, 40).map((entry) => ({ name: entry.name, type: entry.type, size: entry.size }))
    : [];
  return { readme: readmeText, readmeBytes: readme.bytes, files, filesBytes: tree.bytes };
}

/**
 * Turns a repository into editorial text. This is the "article" the blog shows: a lede, a
 * short body and a verdict. It is derived, not generated by an LLM - the blog must work with
 * no API key at all.
 */
export function describeRepository(repo, detail) {
  const readmeParagraphs = (detail.readme ?? '')
    // Drop HTML blocks, images/badges, GitHub alert markers, link-list lines and code fences:
    // none of it is prose a reader wants in the lede.
    .replace(/<[^>]+>/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/^\s*>?\s*\[!(IMPORTANT|WARNING|NOTE|TIP|CAUTION)\]\s*/gim, '')
    .replace(/```[\s\S]*?```/g, ' ')
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.replace(/^#+\s*/, '').replace(/[*_`>#|\-]+/g, ' ').replace(/\s+/g, ' ').trim())
    .filter(
      (paragraph) =>
        paragraph.length > 80 &&
        !/^[|\s]+$/.test(paragraph) &&
        !/badge|shields\.io|CI status|build passing/i.test(paragraph) &&
        !/^github\.com|^npm (package|install)/i.test(paragraph) &&
        (paragraph.match(/[a-z]{3,}/gi) ?? []).length > 12
    )
    .sort((a, b) => b.length - a.length)
    .slice(0, 2);

  const freshnessDays = repo.pushedAt ? Math.round((Date.now() - Date.parse(repo.pushedAt)) / 86400000) : null;
  const languages = [...new Set([repo.language, ...repo.topics].filter(Boolean))];
  const activity = freshnessDays === null ? 'release cadence unknown' : `last push ${freshnessDays} day${freshnessDays === 1 ? '' : 's'} ago`;

  const lede = readmeParagraphs[0] ?? repo.description ?? 'No description in the README.';
  const why = [
    `${formatStars(repo.stars)} stars, ${repo.forks} forks`,
    activity,
    repo.license ? `licensed under ${repo.license}` : 'no declared licence'
  ].join(', ');

  return {
    lede,
    body: readmeParagraphs[1] ?? '',
    why,
    tags: languages.slice(0, 5),
    files: detail.files.slice(0, 12)
  };
}

/**
 * Ranks repositories into "best posts". A blog that only lists giants is useless, so the
 * score rewards being *alive and used* rather than merely old and famous:
 *
 *  - freshness (recent push) and momentum (stars per day since creation) matter most;
 *  - an absurd star count is penalised, because that is the usual signature of a repo whose
 *    social graph was gamed rather than one people actually use;
 *  - forks and issues signal real adoption, which a star-only ranking hides.
 */
export function rankRepositories(repositories) {
  return [...repositories]
    .map((repo) => {
      const createdDays = repo.createdAt ? Math.max(1, (Date.now() - Date.parse(repo.createdAt)) / 86400000) : 365;
      const freshDays = repo.pushedAt ? Math.max(0, (Date.now() - Date.parse(repo.pushedAt)) / 86400000) : 365;
      const freshness = Math.max(0, 1 - freshDays / 120);
      const starsPerDay = Math.min(1, repo.stars / createdDays / 40);
      const adoption = Math.min(1, Math.log10(1 + repo.forks) / 4);
      const suspicion = repo.stars / createdDays > 300 ? 0.2 : 1;
      const score = (0.45 * freshness + 0.3 * starsPerDay + 0.25 * adoption) * suspicion;
      return { ...repo, score: Math.round(score * 1000) / 1000 };
    })
    .sort((a, b) => b.score - a.score);
}

export function formatStars(value) {
  if (value >= 1000) {
    return `${(value / 1000).toFixed(value >= 10000 ? 0 : 1)}k`;
  }
  return String(value);
}
